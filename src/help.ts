export function formatHelpTopic(topicName: string): string {
  const normalized = topicName.trim().toLowerCase();

  if (!normalized || normalized === "overview") {
    return formatHelpOverview();
  }

  const architectureTopic = parseArchitectureHelpTopic(normalized);

  if (architectureTopic !== null) {
    return formatArchitectureOverview(architectureTopic);
  }

  if (normalized === "all" || normalized === "full") {
    return formatHelp();
  }

  const topic = HELP_TOPICS.find(
    (item) => item.name === normalized || item.aliases?.includes(normalized),
  );

  if (!topic) {
    return [
      `Unknown help topic: ${topicName}`,
      "",
      formatHelpOverview(),
    ].join("\n");
  }

  return topic.lines.join("\n");
}

function parseArchitectureHelpTopic(normalized: string): string | null {
  for (const command of ["architecture", "arch", "flow"]) {
    const prefix = `${command} `;

    if (normalized.startsWith(prefix)) {
      return normalized.slice(prefix.length).trim();
    }
  }

  return null;
}

export function formatCompletionHelp(): string {
  return formatHelpTopic("completion");
}

export function getHelpTopicNames(): string[] {
  return [...HELP_TOPICS.map((topic) => topic.name), "all"].sort((left, right) => left.localeCompare(right));
}

